namespace DrakkarVpn.Core.Api.Modules.Admin.Application.DTOs;

/// <summary>
/// Тип того, КАК именно была решена проблема, из-за которой сработал CoreAlert.
/// Хранится на алерте, чтобы потом можно было смотреть статистику по типам решений
/// и переиспользовать готовые кейсы.
/// </summary>
public enum CoreAlertResolutionType
{
    /// <summary>
    /// Тип решения не указан.
    /// Используется по умолчанию, если админ просто закрыл алерт без детализации.
    /// </summary>
    Unknown = 0,

    /// <summary>
    /// Ложное срабатывание: алерт не отражает реальной проблемы.
    /// Например: тестовые нагрузки, разовый всплеск, криво настроенный мониторинг.
    /// </summary>
    FalsePositive = 1,

    /// <summary>
    /// Пороговые значения/настройки мониторинга были изменены.
    /// Например: повышен лимит трафика, RPS или latency, чтобы алерт больше не стрелял
    /// на нормальное поведение системы.
    /// </summary>
    ThresholdAdjusted = 2,

    /// <summary>
    /// Проблема решена перезапуском инфраструктуры.
    /// Например: рестарт сервера, контейнера, агента, балансировщика.
    /// </summary>
    InfraRestarted = 10,

    /// <summary>
    /// Проблема решена заменой инфраструктурного компонента.
    /// Например: переезд на новый сервер, смена региона, замена провайдера внутри DC.
    /// </summary>
    InfraReplaced = 11,

    /// <summary>
    /// Проблема решена правкой конфигурации инфраструктуры.
    /// Например: MTU, лимиты соединений, sysctl, firewall, маршруты.
    /// </summary>
    InfraConfigFixed = 12,
    
    
    // Добавили мощности: новый сервер/регион/шардинг
    InfraCapacityIncreased = 13,

    /// <summary>
    /// Проблема решена фиксом багов в коде.
    /// Например: исправлен handler, баг в воркере, некорректная логика расчёта метрик.
    /// </summary>
    CodeBugFixed = 20,

    /// <summary>
    /// Проблема устранена откатом на предыдущую версию приложения.
    /// Например: rollback деплоя, возврат предыдущего образа/релиза.
    /// </summary>
    CodeRolledBack = 21,

    /// <summary>
    /// Проблема решена ревоком конкретного peer'а.
    /// Например: подозрительная активность, подозрение на шеру/слив, нарушение правил.
    /// </summary>
    PeerRevoked = 30,

    /// <summary>
    /// Пользователю вынесено предупреждение, без жёстких ограничений.
    /// Например: письмо/сообщение в поддержку о нарушении правил использования.
    /// </summary>
    UserWarned = 31,

    /// <summary>
    /// Пользователю частично ограничили функциональность.
    /// Например: ограничение скорости, лимит по трафику, временный блок отдельных действий.
    /// </summary>
    UserRestricted = 32,

    /// <summary>
    /// Пользователь забанен.
    /// Например: за грубое нарушение правил, мошенничество, resale аккаунта.
    /// </summary>
    UserBanned = 33,

    /// <summary>
    /// Проблема на стороне внешнего провайдера.
    /// Например: падение DC, проблемы аплинка, сбой у платёжного провайдера.
    /// Устраняется через тикет/ожидание, а не внутренними действиями.
    /// </summary>
    ExternalProviderIssue = 40,

    /// <summary>
    /// Алерт закрылся автоматически.
    /// Например: метрики вернулись в норму, health-check снова зелёный,
    /// авто-воркер сам пометил алерт как решённый.
    /// </summary>
    AutoResolved = 50
}