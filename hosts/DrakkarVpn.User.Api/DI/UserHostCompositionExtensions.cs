using DrakkarVpn.HostInfrastructure;
using DrakkarVpn.Idempotency;
using DrakkarVpn.Observability;
using DrakkarVpn.Peers;
using DrakkarVpn.Servers;
using DrakkarVpn.Shared.InstanceProvider;
using DrakkarVpn.Subscriptions;
using DrakkarVpn.Tariffs;
using DrakkarVpn.Users;
using DrakkarVpn.Core.Api.Modules.Orchestrator.Application.Abstractions;
using DrakkarVpn.Core.Api.Modules.Orchestrator.Application.Services;
using Idempotency;

namespace DrakkarVpn.Core.Api.Extensions;

public static class UserHostCompositionExtensions
{
    public static IServiceCollection AddUserHostComposition(
        this IServiceCollection services,
        IConfiguration configuration)
    {
        // shared infra
        services.AddHttpClient();
        services.AddAutoGeneratedLinks(configuration);
        services.AddRedis(configuration);
        services.AddMemoryCache();

        // modules infrastructure
        services.AddObservabilityInfrastructure(configuration);
        services.AddUsersInfrastructure(configuration);
        services.AddPeersInfrastructure(configuration);
        services.AddServersInfrastructure(configuration);
        services.AddSubscriptionsInfrastructure(configuration);
        services.AddIdempotencyInfrastructure(configuration);
        services.AddTariffsInfrastructure(configuration);
        services.AddSingleton<IInstanceIdProvider, InstanceIdProvider>();
        

        // host-specific module services
        services.AddObservabilityUserHost();
        services.AddUsersUserHost(configuration);
        services.AddPeersUserHost();
        services.AddServersUserHost();
        services.AddSubscriptionsUserHost();
        services.AddTariffsUserHost();

        // vpn config flow: access context
        services.AddScoped<IVpnAccessContextService, VpnAccessContextService>();
        services.AddScoped<ICurrentVpnConfigService, CurrentVpnConfigService>();
        services.AddScoped<IConfigProvisionService, ConfigProvisionService>();
        services.AddScoped<IHomeContextService, HomeContextService>();

        // pipelines
        services.AddUserHostPipelines();
        services.AddIdempotencyPipeline();

        // workers
        services.AddPeersWorkersUserHost();

        return services;
    }
}